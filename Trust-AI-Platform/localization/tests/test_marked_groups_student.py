class MarkedGroupsStudentTest(SimpleTestCase):
    def assertAllMarked(self, strings):
        marked = marked_msgids()
        missing = [s for s in strings if s not in marked]
        self.assertEqual(missing, [], f'not marked for translation: {missing}')

    def test_page_strings_are_marked(self):
        for page, strings in SENTINELS.items():
            with self.subTest(page=page):
                self.assertAllMarked(strings)

    def test_python_messages_are_marked(self):
        self.assertAllMarked(PYTHON_SENTINELS)

    def test_script_strings_are_marked(self):
        self.assertAllMarked(SCRIPT_SENTINELS)

    def test_placeholder_strings_have_their_own_keys(self):
        for page, strings in SENTINELS.items():
            if any('%(' in s for s in strings):
                self.assertTrue(
                    page.endswith('_msgids'),
                    f'{page}: placeholder strings belong under a key ending in _msgids',
                )

    def test_help_strings_keep_their_old_english_wording(self):
        # Task 12 seeds the translations of these from the retired
        # studentview/help_labels.py, so the msgids must match exactly.
        self.assertAllMarked([
            'Ask for help',
            'Paused: help requested',
            'Your teacher has been asked for help. You can continue when you are ready.',
            'Resume',
            'Could not pause the scenario. Please try again.',
            'Could not resume the scenario. Please try again.',
        ])
